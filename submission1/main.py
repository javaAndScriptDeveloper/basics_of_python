# Implement task here
# 1. Зчитування двох чисел з клавіатури
# Використовуємо float, щоб програма могла працювати і з цілими, і з дробовими числами
try:
    a = float(input("Введіть перше число: "))
    b = float(input("Введіть друге число: "))

    # 2. Виконання арифметичних операцій
    sum_res = a + b
    sub_res = a - b
    mul_res = a * b

    # Перевірка на ділення на нуль
    if b != 0:
        div_res = a / b
    else:
        div_res = "помилка (ділення на нуль неможливе)"

    # 3. Визначення більшого з двох чисел (індивідуальне завдання)
    if a > b:
        max_val = a
    elif b > a:
        max_val = b
    else:
        max_val = "числа рівні"

    # 4. Виведення результатів
    print("\n--- Результати обчислень ---")
    print(f"Додавання: {a} + {b} = {sum_res}")
    print(f"Віднімання: {a} - {b} = {sub_res}")
    print(f"Множення: {a} * {b} = {mul_res}")
    print(f"Ділення: {a} / {b} = {div_res}")
    print(f"Найбільше число: {max_val}")

except ValueError:
    print("Помилка: будь ласка, вводьте лише числа.")