# Варіант 5: перевірка коректності телефонного номера

import re

def is_valid_phone(phone):
    # Видаляємо пробіли, дефіси та дужки
    normalized = re.sub(r'[\s\-\(\)]', '', phone)

    # Перевіряємо формат:
    # +380XXXXXXXXX або 0XXXXXXXXX
    pattern = r'^(?:\+380\d{9}|0\d{9})$'

    return bool(re.fullmatch(pattern, normalized))


# Ввід номера
phone = input("Введіть телефонний номер: ")

# Перевірка
if is_valid_phone(phone):
    print("Коректний телефонний номер")
else:
    print("Некоректний телефонний номер")